// ── Firebase client config ────────────────────────────────────────────────────────────
// Public Firebase identifiers come from the gitignored firebase/app-config.json (template:
// firebase/app-config.example.json) and are compiled into a generated Kotlin object. Without
// the file every value is blank and Firebase is skipped: the app shows a "not configured"
// state and can never talk to somebody else's project. No secret belongs in that file.
val firebaseConfigText: Provider<String> = providers
    .fileContents(rootProject.layout.projectDirectory.file("firebase/app-config.json"))
    .asText
    .orElse("")
val firebaseConfigDir: Provider<Directory> = layout.buildDirectory.dir("generated/firebaseConfig/kotlin")
val generateFirebaseConfig = tasks.register("generateFirebaseConfig") {
    description = "Generates FirebaseAppConfig.kt from firebase/app-config.json."
    inputs.property("config", firebaseConfigText)
    outputs.dir(firebaseConfigDir)
    val configText = firebaseConfigText
    val outputDir = firebaseConfigDir
    doLast {
        val config = configText.get()
        fun value(key: String): String =
            Regex("\"?$key\"?\\s*:\\s*\"([^\"]*)\"").find(config)?.groupValues?.get(1).orEmpty().trim()
        fun literal(text: String): String =
            "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val fields = listOf(
            "API_KEY" to "apiKey",
            "AUTH_DOMAIN" to "authDomain",
            "PROJECT_ID" to "projectId",
            "STORAGE_BUCKET" to "storageBucket",
            "SENDER_ID" to "messagingSenderId",
            "WEB_APP_ID" to "appId",
            "ANDROID_APP_ID" to "androidAppId",
            "IOS_APP_ID" to "iosAppId",
            "EMULATOR_HOST" to "emulatorHost",
            "ANDROID_EMULATOR_HOST" to "androidEmulatorHost",
            "FUNCTIONS_REGION" to "functionsRegion",
            // "true" once the email / WhatsApp sender (Cloud Functions) is deployed for this project.
            "EMAIL_DELIVERY" to "emailDelivery",
            "WHATSAPP_DELIVERY" to "whatsappDelivery",
        )
        val file = outputDir.get().file("com/example/checkinoutapp/firebase/FirebaseAppConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            buildString {
                appendLine("// GENERATED by :shared:generateFirebaseConfig from firebase/app-config.json. Do not edit.")
                appendLine("package com.example.checkinoutapp.firebase")
                appendLine()
                appendLine("internal object FirebaseAppConfig {")
                fields.forEach { (name, key) ->
                    // Callable functions default to us-central1, like the backend.
                    val text = value(key).ifBlank { if (name == "FUNCTIONS_REGION") "us-central1" else "" }
                    appendLine("    const val $name: String = ${literal(text)}")
                }
                appendLine("}")
            },
        )
    }
}

